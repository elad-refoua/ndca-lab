export function iconSvg(name) {
  const body = P[name] || '';
  return `<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">${body}</svg>`;
}

export function icon(name, extraClass = '') {
  const span = document.createElement('span');
  span.className = `icon ${extraClass}`.trim();
  span.innerHTML = iconSvg(name);
  return span;
}

// Fill every <span class="icon" data-icon="..."> already in the HTML.
export function hydrateIcons(root = document) {
  root.querySelectorAll('.icon[data-icon]').forEach((el) => {
    if (!el.firstChild) el.innerHTML = iconSvg(el.dataset.icon);
  });
}

export function setIcon(el, name) {
  const target = el.classList && el.classList.contains('icon') ? el : el.querySelector('.icon');
  if (target) target.innerHTML = iconSvg(name);
}
